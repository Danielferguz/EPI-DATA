// Validación de los motores JS frente a statsmodels/scipy (tests/reference.json, generado con tools/make_reference.py).
import { readFileSync } from 'node:fs';
import { parseCSV } from '../js/io.js';
import { inferMeta, typedData, design, response, completeRows } from '../js/data.js';
import { fitOLS, fitGLM, fitCox, fitGEE, fitLMM, km, logrank } from '../js/models.js';
import { shapiro, chisqTest, fisher2x2, welch, mannWhitney, kruskal } from '../js/tests.js';
import { littleMCAR, mice, pool } from '../js/missing.js';
import { pt, qt, pchisqU, qnorm, pfU, qchisq } from '../js/dist.js';

const here = new URL('.', import.meta.url);
const ref = JSON.parse(readFileSync(new URL('reference.json', here)));
const rows = parseCSV(readFileSync(new URL('sim.csv', here), 'utf8'));
const meta = inferMeta(rows); meta.z.type = 'num'; meta.ybin.event = '1';
const ds = typedData(rows, meta), all = completeRows(ds, Object.keys(meta).filter(v => !['x1m', 'ycm'].includes(v)));
const terms = [{ vars: ['x1'] }, { vars: ['z'] }, { vars: ['g'] }];
const D = design(ds, meta, terms, all);
let fails = 0, checks = 0;
const close = (name, a, b, tol = 1e-5) => {
  const A = (ArrayBuffer.isView(a) ? Array.from(a) : [].concat(a)).map(Number), B = [].concat(b);
  const ok = A.length === B.length && A.every((v, i) => Math.abs(v - B[i]) <= tol * Math.max(1, Math.abs(B[i])));
  checks++; if (!ok) { fails++; console.log('FAIL', name, A, B); } else console.log('ok  ', name);
};
const f = fitOLS(D.X, response(ds, meta.ycont, all));
close('OLS beta', f.beta, ref.ols.beta); close('OLS se', f.se, ref.ols.se); close('OLS R2', f.r2, ref.ols.r2); close('OLS AIC (como R: cuenta sigma)', f.aic, ref.ols.aic + 2);
close('OLS HC3', fitOLS(D.X, response(ds, meta.ycont, all), { robust: 'HC3' }).se, ref.ols.hc3);
const lg = fitGLM(D.X, response(ds, meta.ybin, all), 'binomial');
close('logit beta', lg.beta, ref.logit.beta); close('logit se', lg.se, ref.logit.se); close('logit ll', lg.ll, ref.logit.ll);
const pr = fitGLM(D.X, response(ds, meta.ybin, all), 'poisson', { robust: true });
close('Poisson robusta beta', pr.beta, ref.poisrob.beta); close('Poisson robusta se (HC0)', pr.se, ref.poisrob.se);
const Dc = design(ds, meta, terms, all, { intercept: false });
const cx = fitCox(Dc.X, response(ds, meta.time, all), response(ds, meta.status, all));
close('Cox beta', cx.beta, ref.cox.beta); close('Cox se', cx.se, ref.cox.se); close('Cox ll', cx.ll, ref.cox.ll);
const Dl = design(ds, meta, [{ vars: ['t'] }, { vars: ['z'] }], all); meta.t.type = 'num';
const Dl2 = design(ds, meta, [{ vars: ['t'] }, { vars: ['z'] }], all);
const ge = fitGEE(Dl2.X, response(ds, meta.ylong, all), all.map(i => ds.cols.id[i]), 'gaussian', 'exchangeable');
close('GEE beta', ge.beta, ref.gee.beta, 1e-4); close('GEE se robusto', ge.se, ref.gee.se, 1e-4); close('GEE alpha', ge.alpha, ref.gee.alpha, 1e-4);
const gb = fitGEE(Dl2.X, response(ds, meta.ybin, all), all.map(i => ds.cols.id[i]), 'binomial', 'exchangeable');
close('GEE logit beta', gb.beta, ref.geebin.beta, 1e-4); close('GEE logit se', gb.se, ref.geebin.se, 1e-4);
const lm = fitLMM(Dl2.X, response(ds, meta.ylong, all), all.map(i => ds.cols.id[i]));
close('LMM beta', lm.beta, ref.lmm.beta, 1e-4); close('LMM se', lm.se, ref.lmm.se, 1e-3); close('LMM tau2', lm.tau2, ref.lmm.tau2, 1e-3); close('LMM sigma2', lm.sigma2, ref.lmm.sigma2, 1e-3);
const x1 = Array.from(ds.cols.x1);
ref.shapiro.forEach(([W, p], k) => { const s = shapiro(x1.slice(0, [3, 7, 20, 300][k])); close(`Shapiro n=${[3, 7, 20, 300][k]}`, [s.W, s.p], [W, p], 1e-4); });
const lv = ['A', 'B', 'C'], tab = lv.map(g => [0, 1].map(y => all.filter(i => ds.cols.g[i] === g && ds.cols.ybin[i] === String(y)).length));
const cs = chisqTest(tab); close('chi²', [cs.stat, cs.p], ref.chisq);
close('Fisher', fisher2x2([[3, 9], [8, 2]]).p, ref.fisher);
const xz1 = all.filter(i => ds.cols.z[i] === 1).map(i => ds.cols.x1[i]), xz0 = all.filter(i => ds.cols.z[i] === 0).map(i => ds.cols.x1[i]);
close('Welch', welch(xz1, xz0).p, ref.welch); close('Mann-Whitney', mannWhitney(xz1, xz0).p, ref.mw);
close('Kruskal-Wallis', kruskal(lv.map(g => all.filter(i => ds.cols.g[i] === g).map(i => ds.cols.x1[i]))).p, ref.kw);
close('distribuciones', [pt(-2.1, 7), qt(.975, 13), pchisqU(7.3, 3), qnorm(.001), pfU(2.7, 3, 40), qchisq(.95, 4)], Object.values(ref.dist), 1e-7);
const lr = logrank(response(ds, meta.time, all), response(ds, meta.status, all), all.map(i => ds.cols.g[i]));
close('log-rank', [lr.chisq, lr.p], ref.logrank);
const k = km(response(ds, meta.time, all), response(ds, meta.status, all));
close('KM S(10)', k.steps.filter(s => s.t <= 10).pop().surv, ref.km.surv_at_10); close('KM mediana', k.median, ref.km.median);
const mc = littleMCAR(ds, meta, ['x1m', 'ycm', 'z']); close('MCAR de Little', [mc.stat, mc.df, mc.p], ref.little, 1e-5);
// MICE: comprobación de humo (reproducible con semilla, sin perdidos tras imputar) y reglas de Rubin
const mi = await mice(ds, meta, { vars: ['x1m', 'ycm', 'z', 'g', 'ybin'], m: 5, maxit: 5, seed: 1 });
checks++; if (mi.imps.some(d => Array.from(d.cols.x1m).some(v => !isFinite(v)))) { fails++; console.log('FAIL MICE deja perdidos'); } else console.log('ok   MICE completa los datos');
const fits = mi.imps.map(d => fitOLS(design(d, meta, [{ vars: ['x1m'] }], all).X, response(d, meta.ycm, all)));
const P = pool(fits, all.length - 2); close('Rubin: media de betas', P.beta[1], fits.reduce((a, f) => a + f.beta[1], 0) / 5, 1e-12);
console.log(`\n${checks - fails}/${checks} comprobaciones correctas`);
process.exit(fails ? 1 : 0);
